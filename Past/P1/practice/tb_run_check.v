module tb_run_check;

	reg clk;
	reg res_n;
	reg number;
	wire check;
	integer errors, checks, k;
	reg [8*32:1] name;
	reg prev;

	run_check uut (
		.clk(clk),
		.res_n(res_n),
		.number(number),
		.check(check)
	);

	always #10 clk = ~clk;

	// asynchronous reset between two clock edges; check must drop to 0 immediately
	task rst(input [8*32:1] seq_name);
	begin
		name = seq_name;
		k = 0;
		res_n = 0;
		#2;
		checks = checks + 1;
		if (check !== 1'b0) begin
			errors = errors + 1;
			if (errors <= 10) $display("FAIL: check = %b during reset, expected 0", check);
		end
		#2;
		res_n = 1;
	end
	endtask

	// one bit per clock: change number after a falling edge, look at check just after the rising edge
	task b(input bit_in, input expected);
	begin
		number = bit_in;
		k = k + 1;
		#1;
		if (k > 1 && check !== prev) begin
			errors = errors + 1;
			if (errors <= 10) $display("FAIL: sequence %0s: check changed between clock edges", name);
		end
		@(posedge clk);
		#1;
		checks = checks + 1;
		if (check !== expected) begin
			errors = errors + 1;
			if (errors <= 10) $display("FAIL: sequence %0s, after bit %0d: check = %b, expected %b", name, k, check, expected);
		end
		prev = expected;
		@(negedge clk);
	end
	endtask

