module tb_stack;

	reg clk;
	reg rst;
	reg push;
	reg pop;
	reg [7:0] din;
	wire [7:0] top;
	wire [3:0] count;
	wire err;
	integer errors, checks, n;
	reg [8*48:1] label;
	reg [7:0] prev_top;
	reg [3:0] prev_count;
	reg [0:0] prev_err;

	stack uut (
		.clk(clk),
		.rst(rst),
		.push(push),
		.pop(pop),
		.din(din),
		.top(top),
		.count(count),
		.err(err)
	);

	always #10 clk = ~clk;

	task fail(input [8*40:1] what, input [7:0] e_top, input [3:0] e_count, input [0:0] e_err);
	begin
		errors = errors + 1;
		if (errors <= 10) $display("FAIL: [%0s] step %0d %0s: top = %0d, count = %0d, err = %0d, expected top = %0d, count = %0d, err = %0d",
			label, n, what, top, count, err, e_top, e_count, e_err);
	end
	endtask

	task do_reset(input [8*48:1] new_label);
	begin
		label = new_label;
		n = 0;
		rst = 1;
		#2;
		checks = checks + 1;
		if (top !== 0 || count !== 0 || err !== 0) fail("during reset (must clear immediately)", 0, 0, 0);
		#2;
		rst = 0;
		prev_top = 0;
		prev_count = 0;
		prev_err = 0;
	end
	endtask

	// one clock: push, pop, din
	task s(input pu, input po, input [7:0] d, input [7:0] e_top, input [3:0] e_count, input [0:0] e_err);
	begin
		push = pu;
		pop = po;
		din = d;
		n = n + 1;
		#1;
		checks = checks + 1;
		if (n > 1 && (top !== prev_top || count !== prev_count || err !== prev_err)) fail("between clock edges", prev_top, prev_count, prev_err);
		@(posedge clk);
		#1;
		checks = checks + 1;
		if (top !== e_top || count !== e_count || err !== e_err) fail("", e_top, e_count, e_err);
		prev_top = e_top;
		prev_count = e_count;
		prev_err = e_err;
		@(negedge clk);
	end
	endtask

