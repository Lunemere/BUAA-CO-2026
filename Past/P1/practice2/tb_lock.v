module tb_lock;

	reg clk;
	reg rst;
	reg key_valid;
	reg [3:0] key;
	wire open;
	wire locked;
	integer errors, checks, n;
	reg [8*48:1] label;
	reg [0:0] prev_open;
	reg [0:0] prev_locked;

	lock uut (
		.clk(clk),
		.rst(rst),
		.key_valid(key_valid),
		.key(key),
		.open(open),
		.locked(locked)
	);

	always #10 clk = ~clk;

	task fail(input [8*40:1] what, input [0:0] e_open, input [0:0] e_locked);
	begin
		errors = errors + 1;
		if (errors <= 10) $display("FAIL: [%0s] step %0d %0s: open = %0d, locked = %0d, expected open = %0d, locked = %0d",
			label, n, what, open, locked, e_open, e_locked);
	end
	endtask

	task do_reset(input [8*48:1] new_label);
	begin
		label = new_label;
		n = 0;
		rst = 1;
		#2;
		checks = checks + 1;
		if (open !== 0 || locked !== 0) fail("during reset (must clear immediately)", 0, 0);
		#2;
		rst = 0;
		prev_open = 0;
		prev_locked = 0;
	end
	endtask

	// one clock: key_valid and key
	task k(input v, input [3:0] kk, input [0:0] e_open, input [0:0] e_locked);
	begin
		key_valid = v;
		key = kk;
		n = n + 1;
		#1;
		checks = checks + 1;
		if (n > 1 && (open !== prev_open || locked !== prev_locked)) fail("between clock edges", prev_open, prev_locked);
		@(posedge clk);
		#1;
		checks = checks + 1;
		if (open !== e_open || locked !== e_locked) fail("", e_open, e_locked);
		prev_open = e_open;
		prev_locked = e_locked;
		@(negedge clk);
	end
	endtask

