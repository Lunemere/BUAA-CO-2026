module tb_calc;

	reg clk;
	reg rst;
	reg [7:0] chr;
	wire [15:0] result;
	wire error;
	integer errors, checks, n;
	reg [8*48:1] label;
	reg [15:0] prev_result;
	reg [0:0] prev_error;

	calc uut (
		.clk(clk),
		.rst(rst),
		.chr(chr),
		.result(result),
		.error(error)
	);

	always #10 clk = ~clk;

	task fail(input [8*40:1] what, input [15:0] e_result, input [0:0] e_error);
	begin
		errors = errors + 1;
		if (errors <= 10) $display("FAIL: [%0s] step %0d %0s: result = %0d, error = %0d, expected result = %0d, error = %0d",
			label, n, what, result, error, e_result, e_error);
	end
	endtask

	task do_reset(input [8*48:1] new_label);
	begin
		label = new_label;
		n = 0;
		rst = 1;
		#2;
		checks = checks + 1;
		if (result !== 0 || error !== 0) fail("during reset (must clear immediately)", 0, 0);
		#2;
		rst = 0;
		prev_result = 0;
		prev_error = 0;
	end
	endtask

	// one character per clock
	task c(input [7:0] ch, input [15:0] e_result, input [0:0] e_error);
	begin
		chr = ch;
		n = n + 1;
		#1;
		checks = checks + 1;
		if (n > 1 && (result !== prev_result || error !== prev_error)) fail("between clock edges", prev_result, prev_error);
		@(posedge clk);
		#1;
		checks = checks + 1;
		if (result !== e_result || error !== e_error) fail("", e_result, e_error);
		prev_result = e_result;
		prev_error = e_error;
		@(negedge clk);
	end
	endtask

